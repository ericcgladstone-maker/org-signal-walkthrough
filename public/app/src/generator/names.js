export function slug(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}
export function ascii(s) { return s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/ü/g, 'u'); }

// Unique display names. Labels stay unique within one world because several
// formats (WhatsApp, LinkedIn, survey rosters) identify people only by name.
export function makePeopleNames(rng, n) {
  const used = new Set();
  const first = [], last = [], label = [];
  const initials = 'ABCDEFGHJKLMNPRSTVW';
  for (let i = 0; i < n; i++) {
    let f, l, lab, tries = 0;
    do {
      f = rng.pick(FIRST); l = rng.pick(LAST);
      lab = tries < 6 ? `${f} ${l}` : tries < 40 ? `${f} ${initials[rng.int(initials.length)]}. ${l}` : `${f} ${l}-${rng.pick(LAST)}`;
      tries++;
    } while (used.has(lab) && tries < 200);
    if (used.has(lab)) lab = `${f} ${l} ${i}`;
    used.add(lab);
    first.push(f); last.push(l); label.push(lab);
  }
  return { first, last, label };
}

// Handles like `mossy_heron42`, unique within a world.
export function makeHandles(rng, n, { bots } = {}) {
  const used = new Set(), out = [];
  for (let i = 0; i < n; i++) {
    let h;
    do {
      if (bots && bots[i]) h = `${rng.pick(NOUN)}${rng.digits(7)}`;
      else {
        const style = rng.int(4);
        h = style === 0 ? `${rng.pick(ADJ)}_${rng.pick(NOUN)}`
          : style === 1 ? `${rng.pick(ADJ)}${rng.pick(NOUN)}${rng.int(100)}`
          : style === 2 ? `the${rng.pick(NOUN)}${rng.pick(['', '_', 'x'])}${rng.int(1000)}`
          : `${rng.pick(NOUN)}_${rng.pick(ADJ)}`;
      }
      // valid on every platform used here (X: letters, digits and _ up to 15 characters)
    } while (used.has(h) || h.length > 15);
    used.add(h); out.push(h);
  }
  return out;
}

// name.surname@domain, de-duplicated with digits.
export function makeEmails(first, last, domain) {
  const used = new Map(), out = [];
  for (let i = 0; i < first.length; i++) {
    const base = `${ascii(first[i])}.${ascii(last[i])}`.toLowerCase().replace(/[^a-z0-9.]+/g, '');
    const k = used.get(base) || 0;
    used.set(base, k + 1);
    out.push(`${k ? base + k : base}@${domain}`);
  }
  return out;
}
