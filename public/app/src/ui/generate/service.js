// Every call the Generate view makes into the generator and analysis goes
// through here. Generation runs in a module worker (generate.worker.js); if a
// worker cannot be created the same code runs on the main thread (run.js).
//
//   loadContexts()            -> { contexts (normalised), devFallback, error }
//   startGenerate(spec, { onProgress }) -> { promise, cancel, runId }
//   startRecovery({ seed, runId, groundTruth, dataset, settings })
//                             -> Promise<{ report } | { missing[] }>
//     Checks the run `runId`. The worker answers from its own copy when it
//     still holds that run; otherwise groundTruth and dataset (kept in
//     store.generated by the view) are sent to it.

import { normalizeContexts, FALLBACK_CONTEXTS } from '../../builders/generate-spec.js';

export async function loadContexts() {
  try {
    const gen = await import('../../generator/index.js');
    const contexts = normalizeContexts(await gen.listContexts());
    if (!contexts.length) throw new Error('listContexts() returned no contexts');
    return { contexts, devFallback: false, error: null, recoveryAvailable: typeof gen.recoveryCheck === 'function' };
  } catch (e) {
    // Dev-only: lets the form render while the generator is being written.
    return { contexts: normalizeContexts(FALLBACK_CONTEXTS), devFallback: true, error: e.message, recoveryAvailable: false };
  }
}

let worker = null;
let seq = 0;
let workerRun = null; // runId of the dataset run the current worker holds

function getWorker() {
  if (worker) return worker;
  try {
    worker = new Worker(new URL('./generate.worker.js', import.meta.url), { type: 'module' });
  } catch {
    worker = null;
  }
  return worker;
}

function killWorker() {
  if (worker) { worker.terminate(); worker = null; workerRun = null; }
}

export function startGenerate(spec, { onProgress = () => {} } = {}) {
  const id = ++seq;
  let cancel = () => {};
  const promise = new Promise((resolve, reject) => {
    const w = getWorker();
    if (!w) {
      // Main-thread fallback: no cancel mid-run, but the UI still gets the result.
      import('./run.js').then(({ runGenerate }) => runGenerate(spec, onProgress)).then(resolve, reject);
      return;
    }
    const onMsg = ({ data }) => {
      if (data.id !== id) return;
      if (data.type === 'progress') onProgress(data.fraction, data.message);
      else if (data.type === 'done') { cleanup(); if (spec.output !== 'native') workerRun = id; resolve(data.result); }
      // A failed run may have left the worker holding most of the memory it
      // ran out of; start the next one fresh.
      else if (data.type === 'error') { cleanup(); killWorker(); reject(new Error(data.message)); }
    };
    const onErr = e => { cleanup(); killWorker(); reject(new Error(e.message || 'The generator worker failed to start.')); };
    const cleanup = () => { w.removeEventListener('message', onMsg); w.removeEventListener('error', onErr); };
    w.addEventListener('message', onMsg);
    w.addEventListener('error', onErr);
    w.postMessage({ type: 'generate', id, spec });
    // Terminating is the only way to stop synchronous generator code; the
    // next run starts a fresh worker.
    cancel = () => { cleanup(); killWorker(); reject(Object.assign(new Error('Cancelled'), { cancelled: true })); };
  });
  return { promise, cancel: () => cancel(), runId: id };
}

export function startRecovery({ seed = 1, runId = null, groundTruth = null, dataset = null, settings = null } = {}) {
  const w = getWorker();
  const held = w && runId != null && workerRun === runId;
  if (!w) {
    if (!groundTruth || !dataset) return Promise.resolve({ missing: ['a generated dataset in this session'] });
    return import('./run.js').then(({ runRecovery }) => runRecovery(groundTruth, dataset, { seed, settings }));
  }
  if (!held && (!groundTruth || !dataset)) return Promise.resolve({ missing: ['a generated dataset in this session'] });
  const id = ++seq;
  return new Promise((resolve, reject) => {
    const onMsg = ({ data }) => {
      if (data.id !== id) return;
      w.removeEventListener('message', onMsg);
      if (data.type === 'recovery') resolve(data.result); else reject(new Error(data.message));
    };
    w.addEventListener('message', onMsg);
    w.postMessage(held ? { type: 'recovery', id, seed, runId, settings } : { type: 'recovery', id, seed, runId, settings, groundTruth, dataset });
  });
}
